#!/usr/bin/env python3
"""Turn the 'app' section of the family config into BuildCfg.kt and stage assets (+ optional avatars)."""
import json, os, shutil, sys

here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "build")
cands = [os.environ.get("FAMCAL_APP_CONFIG"), os.path.join(here, "..", "config.local.json"),
         os.path.join(here, "..", "config.example.json")]
path = next(p for p in cands if p and os.path.isfile(p))
cfg = json.load(open(path, encoding="utf-8"))
app, fam = cfg.get("app", {}), cfg.get("family", {})
cam = app.get("camera") or {}
url = os.environ.get("FAMCAL_URL") or app.get("server_url") or "http://familycal.local:8091"


def ks(v):
    return json.dumps(str(v), ensure_ascii=False).replace("$", "\\$")


def arr(xs):
    return "arrayOf(" + ", ".join(ks(x) for x in xs) + ")" if xs else "emptyArray<String>()"


co = app.get("color_overrides") or {}
gl, nt = app.get("morning_glance") or {}, app.get("night") or {}
kt = f"""package com.bakerk7.familycalendar
// Generated by gen_config.py from {os.path.basename(path)}; do not edit.
object BuildCfg {{
    const val DEFAULT_URL = {ks(url)}
    const val FAMILY_LETTER = {ks((fam.get("letter") or fam.get("name") or "F")[:1].upper())}
    val PROFILE_ORDER = {arr(app.get("profile_order") or [])}
    val COLOR_IDS = {arr(list(co.keys()))}
    val COLOR_VALUES = {arr(list(co.values()))}
    const val CAMERA_PKG = {ks(cam.get("package") or "")}
    const val CAMERA_RECEIVER = {ks(cam.get("receiver") or "")}
    const val CAMERA_LABEL = {ks(cam.get("label") or "Camera")}
    const val GLANCE_ON = {str(bool(gl.get("enabled", True))).lower()}
    const val GLANCE_WINDOW = {ks(gl.get("start", "05:00") + "-" + gl.get("end", "10:00"))}
    const val EVE_DIM = {str(bool(nt.get("evening_dim", True))).lower()}
    const val EVE_START = {ks(nt.get("evening_start", "19:30"))}
    const val EVE_LEVEL = {ks(str(nt.get("evening_level", 0.35)))}
    const val SLEEP_START = {ks(nt.get("sleep_start", "21:30"))}
    const val SLEEP_END = {ks(nt.get("sleep_end", "06:30"))}
    const val SLEEP_STYLE = {ks(nt.get("screen", "off"))}
    const val WAKE_MIN = {int(nt.get("wake_minutes", 3))}
}}
"""
os.makedirs(os.path.join(out, "gen"), exist_ok=True)
open(os.path.join(out, "gen", "BuildCfg.kt"), "w", encoding="utf-8").write(kt)
dst = os.path.join(out, "assets")
shutil.rmtree(dst, ignore_errors=True)
shutil.copytree(os.path.join(here, "assets"), dst)
ad = app.get("avatar_dir")  # optional folder of av_<profile id>.png photos; otherwise coloured initials are drawn
if ad:
    ad = os.path.join(os.path.dirname(path), ad)
    for f in sorted(os.listdir(ad)) if os.path.isdir(ad) else []:
        if f.startswith("av_") and f.endswith(".png"):
            shutil.copy(os.path.join(ad, f), dst)
sign = app.get("signing") or {}
ksf = os.path.expanduser(os.environ.get("FAMCAL_KEYSTORE") or sign.get("keystore") or "~/.familycal/release.keystore")
ksp = os.path.expanduser(os.environ.get("FAMCAL_KEYSTORE_PASS") or sign.get("password_file") or ksf + ".pass")
open(os.path.join(out, "sign.env"), "w").write(f"KS={json.dumps(ksf)}\nKS_PASS={json.dumps(ksp)}\n")
print("config:", os.path.basename(path), "| camera:", "on" if cam.get("package") else "off")
